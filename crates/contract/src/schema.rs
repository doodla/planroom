/// The first line, or the `$comment`, of every generated file.
pub const GENERATED_HEADER: &str = "GENERATED by cargo xtask gen. Do not edit.";

/// The JSON Schema dialect both views use.
pub const DIALECT: &str = "https://json-schema.org/draft/2020-12/schema";

const ID_BASE: &str = "https://raw.githubusercontent.com/doodla/planroom/main/schema/";

/// One of the two views.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum View {
    /// What Planroom emits: every always-sent field is required.
    Output,
    /// What Planroom accepts: defaulted and optional fields may be left out.
    Input,
}

impl View {
    pub const ALL: [View; 2] = [View::Output, View::Input];

    /// The file name under `schema/`.
    pub const fn file_name(self) -> &'static str {
        match self {
            View::Output => "planroom.v1.schema.json",
            View::Input => "planroom.v1.input.schema.json",
        }
    }

    /// The schema's `$id`: the raw GitHub URL on `main`.
    pub fn id(self) -> String {
        format!("{ID_BASE}{}", self.file_name())
    }
}

/// The view as a JSON value: every contract is a `$defs` entry, sorted by name.
pub fn generate(view: View) -> Value {
    let settings = SchemaSettings::draft2020_12();
    let settings = match view {
        View::Output => settings.for_serialize(),
        View::Input => settings.for_deserialize(),
    };
    let mut generator = settings.into_generator();
    macro_rules! roots {
        ($($ty:ty),* $(,)?) => { $( generator.subschema_for::<$ty>(); )* };
    }
    roots!(
        Envelope,
        ErrorObject,
        ErrorCode,
        Warning,
        WarningCode,
        Command,
        MapReq,
        FocusReq,
        ScanReq,
        WatchReq,
        SchemaReq,
        VersionReq,
        PersonInitReq,
        ServeReq,
        LayoutPut,
        CodeReq,
        DrainReq,
        SessionReq,
        MapView,
        PaneModel,
        ScanResult,
        SchemaSummary,
        CommandList,
        LeafSchema,
        VersionInfo,
        PersonKey,
        ServeInfo,
        OpenReq,
        OpenResult,
        SessionToken,
        StreamFrame,
        Node,
        Edge,
        Evidence,
        Hint,
        FactBatch,
        Event,
        ShareReq,
        ImportReq,
        ShareResult,
        ImportResult,
        ImportLine,
        Snapshot,
        LiveHead,
        InboxRow,
        InboxHead,
        Answer,
        Ack,
        ToolResult,
        ResolverStatus,
        UnavailableReason,
        EngineState,
        PaneState,
        LastSeq,
        TurnSeq,
        EditReq,
        EditResult,
        ReviewReq,
        IntentNextReq,
        ProposeReq,
        LintReq,
        AskReq,
        AskResult,
        FindReq,
        FindResult,
        PackFile,
        PackRecord,
        DoctorReq,
        PackReport,
    );
    // Planroom reads a configuration file and never emits one.
    if view == View::Input {
        generator.subschema_for::<Config>();
    }
    let mut defs: Vec<(String, Value)> = generator.take_definitions(true).into_iter().collect();
    defs.sort_by(|a, b| a.0.cmp(&b.0));
    let (title, description) = match view {
        View::Output => ("Planroom contract v1", "What Planroom emits (the serialize view)."),
        View::Input => ("Planroom contract v1, input", "What Planroom accepts (the deserialize view)."),
    };
    json!({
        "$schema": DIALECT,
        "$id": view.id(),
        "$comment": GENERATED_HEADER,
        "title": title,
        "description": description,
        "$defs": defs.into_iter().collect::<Map<String, Value>>(),
    })
}

/// `pack.toml` in the input view alone: `{"$ref": ...}` to `PackFile` under `root`, and every
/// definition it references under `$defs`. The pack loader walks a manifest against it to refuse a
/// key no table declares, at that key's line, where serde can't name one: in a table an untagged
/// enum reads, or beside a flattened map.
pub fn pack_manifest() -> Value {
    let mut generator = SchemaSettings::draft2020_12().for_deserialize().into_generator();
    let root = generator.subschema_for::<PackFile>();
    let defs: Map<String, Value> = generator.take_definitions(true).into_iter().collect();
    json!({ "root": root, "$defs": defs })
}

/// The mark on a field that holds repo-derived free text, `#[schemars(extend("x-redact" = true))]`:
/// `kernel::redact` masks the secrets in it on every output path (DR-89). An ID, a handle, a
/// cursor or a hash is never marked.
pub const REDACT_MARK: &str = "x-redact";

/// For each type of the output view that holds a marked field, by name, the paths from it to each
/// marked field: property names joined by `.`, with `[]` for an array's items and `{}` for a map's
/// values, such as `nodes[].name`. Both lists are sorted. `cargo xtask gen` writes them into
/// `crates/kernel/src/redact_fields.rs`.
pub fn redacted_paths() -> Vec<(String, Vec<String>)> {
    paths_to(|property| (property.get(REDACT_MARK) == Some(&Value::Bool(true))).then(String::new))
        .into_iter()
        .map(|(name, paths)| (name, paths.into_iter().map(|(path, _)| path).collect()))
        .collect()
}

/// The mark on a type with a `code` and `details`, an error or a warning,
/// `#[schemars(extend("x-redact-details" = "error"))]` or `"warning"`: `kernel::redact` masks the
/// keys of its `details` that the registry's entry for its `code` names in `redact` (DR-89).
pub const REDACT_DETAILS_MARK: &str = "x-redact-details";

/// For each type of the output view that holds an error or a warning, by name, the path to each
/// one, `""` for the type itself, with `error` or `warning` for the registry its `code` is in.
/// Both lists are sorted. `cargo xtask gen` writes them into `crates/kernel/src/redact_fields.rs`
/// beside each code's masked keys.
pub fn redacted_details() -> Vec<(String, Vec<(String, String)>)> {
    paths_to(|schema| schema.get(REDACT_DETAILS_MARK).and_then(Value::as_str).map(str::to_owned))
        .into_iter()
        .map(|(name, paths)| (name, paths.into_iter().collect()))
        .collect()
}

/// For each type of the output view, the paths to each schema `mark` gives a tag, with that tag.
fn paths_to(mark: impl Fn(&Value) -> Option<String>) -> Vec<(String, BTreeSet<(String, String)>)> {
    let root = generate(View::Output);
    let Some(defs) = root["$defs"].as_object() else { return vec![] };
    let mut out = Vec::new();
    for (name, def) in defs {
        let mut paths = BTreeSet::new();
        marked_paths(defs, def, "", &mark, &mut paths);
        if !paths.is_empty() {
            out.push((name.clone(), paths));
        }
    }
    out
}

/// Every path under `schema` to a schema `mark` tags, a property or a type, each prefixed with
/// `path`, with its tag. The contract has no recursive type, so following each `$ref` ends.
fn marked_paths(
    defs: &Map<String, Value>,
    schema: &Value,
    path: &str,
    mark: &dyn Fn(&Value) -> Option<String>,
    out: &mut BTreeSet<(String, String)>,
) {
    if let Some(tag) = mark(schema) {
        out.insert((path.to_owned(), tag));
        return;
    }
    let Some(schema) = schema.as_object() else { return };
    let target = schema.get("$ref").and_then(Value::as_str).and_then(|r| r.strip_prefix("#/$defs/"));
    if let Some(def) = target.and_then(|name| defs.get(name)) {
        marked_paths(defs, def, path, mark, out);
    }
    if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
        for (field, property) in properties {
            let field_path = if path.is_empty() { field.clone() } else { format!("{path}.{field}") };
            marked_paths(defs, property, &field_path, mark, out);
        }
    }
    if let Some(items) = schema.get("items") {
        marked_paths(defs, items, &format!("{path}[]"), mark, out);
    }
    for item in schema.get("prefixItems").and_then(Value::as_array).into_iter().flatten() {
        marked_paths(defs, item, &format!("{path}[]"), mark, out);
    }
    if let Some(values) = schema.get("additionalProperties") {
        marked_paths(defs, values, &format!("{path}{{}}"), mark, out);
    }
    for key in ["oneOf", "anyOf", "allOf"] {
        for branch in schema.get(key).and_then(Value::as_array).into_iter().flatten() {
            marked_paths(defs, branch, path, mark, out);
        }
    }
}

/// The view as the committed file's bytes.
pub fn render(view: View) -> String {
    let mut out = serde_json::to_string_pretty(&generate(view)).expect("a schema serializes");
    out.push('\n');
    out
}
