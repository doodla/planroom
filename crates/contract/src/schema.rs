//! The two schema views of the one contract: what Planroom emits and what it accepts.

use schemars::generate::SchemaSettings;
use serde_json::{Map, Value, json};

use crate::{
    Ack, Answer, ImportLine, ImportReq, ImportResult, InboxHead, InboxRow, LiveHead, ShareReq, ShareResult,
    Snapshot,
};
use crate::{
    CodeReq, Command, CommandList, Edge, Envelope, ErrorCode, ErrorObject, Event, Evidence, FactBatch,
    FocusReq, Hint, LayoutPut, LeafSchema, MapReq, MapView, Node, PaneModel, PersonInitReq, PersonKey,
    ScanReq, ScanResult, SchemaReq, SchemaSummary, ServeInfo, ServeReq, SessionReq, SessionToken,
    StreamFrame, VersionInfo, VersionReq, Warning, WarningCode, WatchReq,
};

/// The first line, or the `$comment`, of every generated file.
pub const GENERATED_HEADER: &str = "GENERATED by cargo xtask gen. Do not edit.";

/// The JSON Schema dialect both views use.
pub const DIALECT: &str = "https://json-schema.org/draft/2020-12/schema";

const ID_BASE: &str = "https://raw.githubusercontent.com/doodla/planroom/main/schema/";

/// One of the two views.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum View {
    /// What Planroom emits: every always-sent field is required.
    Output,
    /// What Planroom accepts: defaulted and optional fields may be left out.
    Input,
}

impl View {
    pub const ALL: [View; 2] = [View::Output, View::Input];

    /// The file name under `schema/`.
    pub const fn file_name(self) -> &'static str {
        match self {
            View::Output => "planroom.v1.schema.json",
            View::Input => "planroom.v1.input.schema.json",
        }
    }

    /// The schema's `$id`: the raw GitHub URL on `main`.
    pub fn id(self) -> String {
        format!("{ID_BASE}{}", self.file_name())
    }
}

/// The view as a JSON value: every contract is a `$defs` entry, sorted by name.
pub fn generate(view: View) -> Value {
    let settings = SchemaSettings::draft2020_12();
    let settings = match view {
        View::Output => settings.for_serialize(),
        View::Input => settings.for_deserialize(),
    };
    let mut generator = settings.into_generator();
    macro_rules! roots {
        ($($ty:ty),* $(,)?) => { $( generator.subschema_for::<$ty>(); )* };
    }
    roots!(
        Envelope,
        ErrorObject,
        ErrorCode,
        Warning,
        WarningCode,
        Command,
        MapReq,
        FocusReq,
        ScanReq,
        WatchReq,
        SchemaReq,
        VersionReq,
        PersonInitReq,
        ServeReq,
        LayoutPut,
        CodeReq,
        SessionReq,
        MapView,
        PaneModel,
        ScanResult,
        SchemaSummary,
        CommandList,
        LeafSchema,
        VersionInfo,
        PersonKey,
        ServeInfo,
        SessionToken,
        StreamFrame,
        Node,
        Edge,
        Evidence,
        Hint,
        FactBatch,
        Event,
        ShareReq,
        ImportReq,
        ShareResult,
        ImportResult,
        ImportLine,
        Snapshot,
        LiveHead,
        InboxRow,
        InboxHead,
        Answer,
        Ack,
    );
    let mut defs: Vec<(String, Value)> = generator.take_definitions(true).into_iter().collect();
    defs.sort_by(|a, b| a.0.cmp(&b.0));
    let (title, description) = match view {
        View::Output => ("Planroom contract v1", "What Planroom emits (the serialize view)."),
        View::Input => ("Planroom contract v1, input", "What Planroom accepts (the deserialize view)."),
    };
    json!({
        "$schema": DIALECT,
        "$id": view.id(),
        "$comment": GENERATED_HEADER,
        "title": title,
        "description": description,
        "$defs": defs.into_iter().collect::<Map<String, Value>>(),
    })
}

/// The view as the committed file's bytes.
pub fn render(view: View) -> String {
    let mut out = serde_json::to_string_pretty(&generate(view)).expect("a schema serializes");
    out.push('\n');
    out
}
