//! The docs checks with data to guard (architecture.md, Art spend; DR-65).

use std::fs;
use std::path::{Path, PathBuf};

use xtask::docs::every_image_has_its_prompt_and_spend_row as check;

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// A temporary root holding `docs/art/` with the given files.
fn art(name: &str, files: &[(&str, &str)]) -> PathBuf {
    let root = std::env::temp_dir().join(format!("planroom-art-{name}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(root.join("docs/art")).unwrap();
    for (path, text) in files {
        fs::write(root.join("docs/art").join(path), text).unwrap();
    }
    root
}

const ROW: &str = r#"{"at": "2026-10-25T00:00:00Z", "image": "logo.png", "model": "m", "cost_usd": 0.05, "prompt_path": "docs/art/logo.prompt.txt"}"#;

#[test]
fn every_image_has_its_prompt_and_spend_row() {
    let found = check(&repo()).unwrap();
    assert!(found.problems.is_empty(), "{:#?}", found.problems);
    assert!(found.total_usd > 0.0 && found.total_usd < 5.0, "{}", found.total_usd);
}

#[test]
fn an_image_without_a_row_fails() {
    let root = art(
        "norow",
        &[("logo.png", "png"), ("hero.png", "png"), ("logo.prompt.txt", "p"), ("spend.jsonl", ROW)],
    );
    let found = check(&root).unwrap();
    assert_eq!(found.problems, ["docs/art/hero.png has no row in docs/art/spend.jsonl"]);
    fs::remove_dir_all(root).unwrap();
}

#[test]
fn a_missing_prompt_fails_and_a_drafts_row_passes() {
    let drafts = r#"{"at": "2026-10-25T00:00:00Z", "image": "drafts", "model": "m", "cost_usd": 0.1, "prompt_path": null}"#;
    let root = art("prompt", &[("logo.png", "png"), ("spend.jsonl", &format!("{ROW}\n{drafts}\n"))]);
    let found = check(&root).unwrap();
    assert_eq!(found.problems.len(), 1, "{:?}", found.problems);
    assert!(found.problems[0].contains("prompt_path docs/art/logo.prompt.txt doesn't exist"));
    fs::remove_dir_all(root).unwrap();
}

#[test]
fn a_total_at_the_cap_fails() {
    let big = ROW.replace("0.05", "5.0");
    let root = art("cap", &[("logo.png", "png"), ("logo.prompt.txt", "p"), ("spend.jsonl", &big)]);
    let found = check(&root).unwrap();
    assert!(found.problems.iter().any(|p| p.contains("not under the $5 cap")), "{:?}", found.problems);
    fs::remove_dir_all(root).unwrap();
}

/// A clone of this repository's HEAD in a temporary directory, removed on drop, since
/// `generated_headers` reads the paths `git ls-files` holds.
struct Clone(PathBuf);

impl Clone {
    fn new(name: &str) -> Self {
        let dir = std::env::temp_dir().join(format!("planroom-docs-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let out = std::process::Command::new("git")
            .args(["clone", "--quiet", "--shared", ".", dir.to_str().unwrap()])
            .current_dir(repo())
            .output()
            .unwrap();
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
        Self(dir)
    }

    fn edit(&self, rel: &str, from: &str, to: &str) {
        let path = self.0.join(rel);
        let text = fs::read_to_string(&path).unwrap();
        assert!(text.contains(from), "{rel} holds no {from:?}");
        fs::write(path, text.replacen(from, to, 1)).unwrap();
    }
}

impl Drop for Clone {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

/// Every path a generator writes, from this repository: a clone at its HEAD holds the same.
fn outputs() -> std::collections::BTreeSet<String> {
    let groups: Vec<_> = xtask::generate::all(&repo()).into_iter().map(Result::unwrap).collect();
    xtask::docs::generator_outputs(&groups)
}

#[test]
fn generated_headers() {
    use xtask::docs::{Shape, generated_table};
    let written = outputs();
    let generated_headers = |root: &Path| xtask::docs::generated_headers(root, Some(&written));
    assert_eq!(generated_headers(&repo()).unwrap(), Vec::<String>::new());

    let c = Clone::new("headers");
    assert_eq!(generated_headers(&c.0).unwrap(), Vec::<String>::new());
    // A generated directory without its stub.
    fs::remove_file(c.0.join("tests/golden/GENERATED.md")).unwrap();
    // A generated file in a hand-written directory without its header.
    c.edit(".dependency-cruiser.cjs", "// GENERATED by cargo xtask gen. Do not edit.", "// written by hand");
    // A path the table names that doesn't exist, without the milestone that builds it.
    c.edit("docs/contributing/repo-layout.md", "`docs/reference/cli.md` (M5)", "`docs/reference/cli.md`");
    let found = generated_headers(&c.0).unwrap();
    assert_eq!(found.len(), 3, "{found:#?}");
    for start in [
        "tests/golden/GENERATED.md: missing",
        ".dependency-cruiser.cjs: no GENERATED header",
        "docs/reference/cli.md: the Generated directories table names it, but nothing is there",
    ] {
        assert!(found.iter().any(|p| p.starts_with(start)), "{start}: {found:#?}");
    }

    // Every path `cargo xtask gen` writes falls under some row of the table.
    let rows = generated_table(&repo()).unwrap();
    for group in xtask::generate::all(&repo()) {
        for file in group.unwrap().files {
            let covered =
                rows.iter().flat_map(|r| r.paths.iter().map(move |p| (r.shape, p))).any(|(shape, p)| {
                    match shape {
                        Shape::Directory => file.path.starts_with(&p.path),
                        _ => xtask::util::path_matches(&p.path, &file.path),
                    }
                });
            assert!(covered, "{} is generated, but no Generated directories row names it", file.path);
        }
    }
}

#[test]
fn a_hand_written_file_in_a_generated_directory_fails() {
    let written = outputs();
    let generated_headers = |root: &Path| xtask::docs::generated_headers(root, Some(&written));
    let c = Clone::new("handwritten");
    for (path, text) in [
        ("packages/contract/src/generated/handwritten.ts", "export const X = 1;\n"),
        ("plugin/types/extra.d.ts", "export {};\n"),
        ("schema/extra.json", "{}\n"),
        ("schema/baseline/extra.json", "{}\n"),
        ("tests/golden/cli/extra.json", "{}\n"),
    ] {
        fs::write(c.0.join(path), text).unwrap();
    }
    let found = generated_headers(&c.0).unwrap();
    for start in [
        "packages/contract/src/generated/handwritten.ts: sits in the generated directory `packages/contract/src/generated/`, but `cargo xtask gen` doesn't write it",
        "plugin/types/extra.d.ts: sits in the generated directory `plugin/types/`, but `cargo xtask gen` doesn't write it",
        "schema/extra.json: sits in the generated directory `schema/`, but `cargo xtask gen` doesn't write it",
        "schema/baseline/extra.json: sits in the generated directory `schema/baseline/`, but `cargo xtask gen --schema-baseline` doesn't write it",
        "tests/golden/cli/extra.json: sits in the generated directory `tests/golden/`, but `cargo xtask gen --golden` doesn't write it",
    ] {
        assert!(found.iter().any(|p| p.starts_with(start)), "{start}: {found:#?}");
    }
    assert_eq!(found.len(), 5, "{found:#?}");
}

#[test]
fn a_stub_leaves_out_a_nested_generated_directory() {
    let group = xtask::docs::generated_marks(&repo()).unwrap();
    let stub = |dir: &str| {
        group.files.iter().find(|f| f.path == format!("{dir}GENERATED.md")).unwrap().contents.clone()
    };
    let outer = stub("schema/");
    assert!(
        outer.contains("except `AGENTS.md`, `CLAUDE.md` and `baseline/`, which has a stub of its own"),
        "{outer}"
    );
    let inner = stub("schema/baseline/");
    assert!(
        inner.contains("`cargo xtask gen --schema-baseline` writes every file in `schema/baseline/`"),
        "{inner}"
    );
}
