//! The area contracts: each area's `AGENTS.md` block, generated from the two area tables in
//! repo-layout.md, and `area_contracts_match_repo_layout` (DR-59, DR-70, DR-79, DR-81).

use std::collections::BTreeSet;
use std::fs;
use std::path::{Component, Path, PathBuf};

use crate::boundaries::Boundaries;
use crate::generate::Generated;
use crate::layout::{self, REPO_LAYOUT};
use crate::util;

pub const BEGIN: &str = "<!-- BEGIN GENERATED by cargo xtask gen from docs/contributing/repo-layout.md's area tables; do not edit -->";
pub const END: &str = "<!-- END GENERATED -->";

/// Directories whose children are the areas.
const CONTAINERS: &[&str] = &["crates", "packages", "tests"];
/// The one area with `AGENTS.md` and no `CLAUDE.md`, since validate --strict warns on it (DR-81).
const NO_CLAUDE_MD: &str = "plugin";
const ARCHITECTURE: &str = "docs/contributing/architecture.md";

/// The cells of the first Markdown table after the line `heading`, header row included and the
/// separator row left out, each cell trimmed with its whitespace runs collapsed, so formatting
/// doesn't count.
pub fn table_rows(text: &str, heading: &str) -> Vec<Vec<String>> {
    let mut lines = text.lines().skip_while(|l| l.trim_end() != heading);
    if lines.next().is_none() {
        return Vec::new();
    }
    lines
        .skip_while(|l| !l.trim_start().starts_with('|'))
        .take_while(|l| l.trim_start().starts_with('|'))
        .map(split_row)
        .filter(|cells| !cells.iter().all(|c| !c.is_empty() && c.chars().all(|ch| ch == '-' || ch == ':')))
        .collect()
}

/// A table row's cells, splitting on `|` outside code spans.
fn split_row(line: &str) -> Vec<String> {
    let inner = line.trim().trim_start_matches('|');
    let inner = inner.strip_suffix('|').unwrap_or(inner);
    let mut cells = Vec::new();
    let (mut cell, mut code) = (String::new(), false);
    for c in inner.chars() {
        match c {
            '`' => {
                code = !code;
                cell.push(c);
            }
            '|' if !code => cells.push(std::mem::take(&mut cell)),
            _ => cell.push(c),
        }
    }
    cells.push(cell);
    cells.into_iter().map(|c| c.split_whitespace().collect::<Vec<_>>().join(" ")).collect()
}

/// One row of the area contracts table.
#[derive(Debug, Clone)]
pub struct Area {
    /// The area's directory from the repo root, such as `crates/kernel`, `packs` or `tests/replay`.
    pub dir: String,
    pub owns: String,
    pub may: String,
    pub must_not: String,
    pub test: String,
}

/// One row of the Read first table, for one area.
#[derive(Debug, Clone)]
struct ReadFirst {
    sections: String,
    records: String,
    scenarios: String,
}

/// `crates/kernel` from `` `crates/kernel` ``; `packs` from `` `packs/*` ``.
fn area_dirs(cell: &str) -> Vec<String> {
    cell.split(", ")
        .map(|d| d.trim().trim_matches('`').trim_end_matches('*').trim_end_matches('/').to_owned())
        .filter(|d| !d.is_empty())
        .collect()
}

pub fn areas(root: &Path) -> Result<Vec<Area>, String> {
    let text = read(root, REPO_LAYOUT)?;
    let rows = table_rows(&text, "## Area contracts");
    let mut out = Vec::new();
    for row in rows.iter().skip(1) {
        let [area, owns, may, must_not, test] = row.as_slice() else {
            return Err(format!(
                "{REPO_LAYOUT}: an area contracts row has {} cells, not 5: {row:?}",
                row.len()
            ));
        };
        for dir in area_dirs(area) {
            out.push(Area {
                dir,
                owns: owns.clone(),
                may: may.clone(),
                must_not: must_not.clone(),
                test: test.clone(),
            });
        }
    }
    if out.is_empty() {
        return Err(format!("{REPO_LAYOUT}: no area contracts table"));
    }
    Ok(out)
}

fn read_first(root: &Path) -> Result<Vec<(String, ReadFirst)>, String> {
    let text = read(root, REPO_LAYOUT)?;
    let mut out = Vec::new();
    for row in table_rows(&text, "### Read first, per area").iter().skip(1) {
        let [area, sections, records, scenarios] = row.as_slice() else {
            return Err(format!("{REPO_LAYOUT}: a Read first row has {} cells, not 4: {row:?}", row.len()));
        };
        for dir in area_dirs(area) {
            out.push((
                dir,
                ReadFirst {
                    sections: sections.clone(),
                    records: records.clone(),
                    scenarios: scenarios.clone(),
                },
            ));
        }
    }
    Ok(out)
}

fn read(root: &Path, path: &str) -> Result<String, String> {
    fs::read_to_string(root.join(path)).map_err(|e| format!("{path}: {e}"))
}

/// GitHub's heading anchor: lowercase, punctuation other than `-` and `_` dropped, spaces as `-`.
pub fn slug(heading: &str) -> String {
    heading
        .trim()
        .to_lowercase()
        .chars()
        .filter_map(|c| match c {
            ' ' => Some('-'),
            c if c.is_alphanumeric() || c == '-' || c == '_' => Some(c),
            _ => None,
        })
        .collect()
}

/// Every heading's text in a Markdown file, at any level, outside code fences.
fn headings(text: &str) -> Vec<String> {
    let mut fenced = false;
    let mut out = Vec::new();
    for line in text.lines() {
        if line.starts_with("```") {
            fenced = !fenced;
        } else if !fenced && line.starts_with('#') {
            let title = line.trim_start_matches('#');
            if title.starts_with(' ') {
                out.push(title.trim().to_owned());
            }
        }
    }
    out
}

/// `../../` for `crates/kernel`, `../` for `plugin`.
fn up(dir: &str) -> String {
    "../".repeat(dir.split('/').count())
}

/// Resolve `.` and `..` without touching the file system.
fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for c in path.components() {
        match c {
            Component::ParentDir => {
                out.pop();
            }
            Component::CurDir => {}
            other => out.push(other),
        }
    }
    out
}

/// Rewrite every relative link in a cell from `docs/contributing/` to the area's directory.
fn relink(cell: &str, area: &str) -> String {
    let mut out = String::new();
    let mut rest = cell;
    while let Some(at) = rest.find("](") {
        out.push_str(&rest[..at + 2]);
        rest = &rest[at + 2..];
        let end = rest.find(')').unwrap_or(rest.len());
        let target = &rest[..end];
        let fixed = if target.starts_with("http") {
            target.to_owned()
        } else if let Some(anchor) = target.strip_prefix('#') {
            format!("{}{REPO_LAYOUT}#{anchor}", up(area))
        } else {
            let (file, anchor) = target.split_once('#').map_or((target, None), |(f, a)| (f, Some(a)));
            let joined = normalize(&Path::new("docs/contributing").join(file));
            let mut t = format!("{}{}", up(area), joined.display());
            if let Some(a) = anchor {
                t.push('#');
                t.push_str(a);
            }
            t
        };
        out.push_str(&fixed);
        rest = &rest[end..];
    }
    out.push_str(rest);
    out
}

/// The Read first lines: each plain section name becomes a link to its heading in architecture.md,
/// failing on a name that matches none; each record a link to its heading in decisions.md.
fn read_first_lines(root: &Path, area: &str, rf: &ReadFirst) -> Result<String, String> {
    let arch = headings(&read(root, ARCHITECTURE)?);
    let mut sections = Vec::new();
    for item in rf.sections.split("; ").map(str::trim).filter(|s| !s.is_empty()) {
        if item.contains("](") || item.starts_with('`') {
            sections.push(relink(item, area));
        } else if arch.iter().any(|h| h == item) {
            sections.push(format!("[{item}]({}{ARCHITECTURE}#{})", up(area), slug(item)));
        } else {
            return Err(format!(
                "{REPO_LAYOUT}: Read first for `{area}` names \"{item}\", which matches no heading in {ARCHITECTURE}"
            ));
        }
    }
    let decisions = layout::record_headings(root)?;
    let mut records = Vec::new();
    for item in rf.records.split(", ").map(str::trim).filter(|s| !s.is_empty()) {
        let n = layout::record_number(item)
            .ok_or_else(|| format!("{REPO_LAYOUT}: Read first for `{area}` names record \"{item}\""))?;
        let (_, heading) = decisions.iter().find(|(h, _)| *h == n).ok_or_else(|| {
            format!("{REPO_LAYOUT}: Read first for `{area}` names {item}, which has no heading")
        })?;
        records.push(format!("[{item}]({}{}#{})", up(area), layout::DECISIONS, slug(heading)));
    }
    Ok(format!(
        "Read first, from [Repo layout]({}{REPO_LAYOUT}#read-first-per-area):\n\n- **Sections:** {}.\n- **Records:** {}.\n- **Scenarios:** {}.\n",
        up(area),
        sections.join("; "),
        records.join(", "),
        rf.scenarios
    ))
}

/// The generated block for one area, markers included.
fn block(root: &Path, area: &Area, rf: Option<&ReadFirst>) -> Result<String, String> {
    let cell = |c: &str| {
        let c = relink(c, &area.dir);
        if c.is_empty() { "nothing".to_owned() } else { c }
    };
    let mut out = format!(
        "{BEGIN}\n\nThis area's contract, from [Repo layout]({}{REPO_LAYOUT}#area-contracts).\n\n- **Owns:** {}.\n- **May depend on:** {}.\n- **Must not:** {}.\n- **How to test it:** {}.\n",
        up(&area.dir),
        cell(&area.owns),
        cell(&area.may),
        cell(&area.must_not),
        cell(&area.test)
    );
    if let Some(rf) = rf {
        out.push('\n');
        out.push_str(&read_first_lines(root, &area.dir, rf)?);
    }
    out.push('\n');
    out.push_str(END);
    Ok(out)
}

/// Place `block` in an `AGENTS.md`: between the markers when they exist; otherwise in place of
/// the hand-written contract (the "This area's contract" line and its bullets), or after the title.
fn place(text: &str, block: &str) -> String {
    if let (Some(b), Some(e)) = (text.find(BEGIN), text.find(END))
        && b < e
    {
        return format!("{}{block}{}", &text[..b], &text[e + END.len()..]);
    }
    let lines: Vec<&str> = text.lines().collect();
    let (start, end) = match lines.iter().position(|l| l.starts_with("This area's contract")) {
        Some(s) => {
            let mut e = s + 1;
            while e < lines.len() && (lines[e].trim().is_empty() || lines[e].starts_with("- **")) {
                if lines[e].trim().is_empty() && !lines.get(e + 1).is_some_and(|n| n.starts_with("- **")) {
                    break;
                }
                e += 1;
            }
            (s, e)
        }
        None => {
            let title = lines.iter().position(|l| l.starts_with("# ")).map_or(0, |t| t + 1);
            (title, title)
        }
    };
    let mut out: Vec<String> = lines[..start].iter().map(|s| s.to_string()).collect();
    if out.last().is_some_and(|l| !l.trim().is_empty()) {
        out.push(String::new());
    }
    out.push(block.to_owned());
    let rest = &lines[end..];
    if rest.first().is_some_and(|l| !l.trim().is_empty()) {
        out.push(String::new());
    }
    out.extend(rest.iter().map(|s| s.to_string()));
    let mut joined = out.join("\n");
    joined.push('\n');
    joined
}

/// Each existing area's `AGENTS.md` with its generated block in place.
pub fn generated(root: &Path) -> Result<Vec<Generated>, String> {
    let rf = read_first(root)?;
    let mut files = Vec::new();
    for area in areas(root)? {
        if !root.join(&area.dir).is_dir() {
            continue;
        }
        let path = format!("{}/AGENTS.md", area.dir);
        let Ok(text) = fs::read_to_string(root.join(&path)) else { continue };
        let read_first = rf.iter().find(|(d, _)| *d == area.dir).map(|(_, r)| r);
        let contents = place(&text, &block(root, &area, read_first)?);
        files.push(Generated { path, contents });
    }
    Ok(files)
}

/// The areas `git ls-files` holds: each non-dot top-level directory, with each container's
/// children in its place.
fn tracked_areas(root: &Path) -> Result<BTreeSet<String>, String> {
    let listed =
        util::capture(root, "git", &["ls-files", "-z", "--cached", "--others", "--exclude-standard"])?;
    let mut out = BTreeSet::new();
    for path in listed.split('\0').filter(|p| !p.is_empty() && root.join(p).exists()) {
        let parts: Vec<&str> = path.split('/').collect();
        if parts.len() < 2 || parts[0].starts_with('.') {
            continue;
        }
        if CONTAINERS.contains(&parts[0]) {
            if parts.len() >= 3 {
                out.insert(format!("{}/{}", parts[0], parts[1]));
            }
        } else {
            out.insert(parts[0].to_owned());
        }
    }
    Ok(out)
}

/// `area_contracts_match_repo_layout`, less the block drift `cargo xtask check`'s drift checks
/// cover: every area has a row, its `AGENTS.md` and its `CLAUDE.md` (none in `plugin/`), and the
/// "May depend on" cells name exactly the allow-lists in `boundaries.toml`.
pub fn problems(root: &Path, rules: &Boundaries) -> Result<Vec<String>, String> {
    let rows = areas(root)?;
    let mut problems = Vec::new();
    for dir in tracked_areas(root)? {
        if !rows.iter().any(|a| a.dir == dir) {
            problems.push(format!("`{dir}/` has no row in {REPO_LAYOUT}'s area contracts table"));
        }
        let agents = root.join(&dir).join("AGENTS.md");
        let claude = root.join(&dir).join("CLAUDE.md");
        match fs::read_to_string(&agents) {
            Ok(text) if text.contains(BEGIN) && text.contains(END) => {}
            Ok(_) => {
                problems.push(format!("{dir}/AGENTS.md has no generated contract block (cargo xtask gen)"))
            }
            Err(_) => problems.push(format!("`{dir}/` has no AGENTS.md")),
        }
        if dir == NO_CLAUDE_MD {
            if claude.exists() {
                problems.push(format!("{dir}/CLAUDE.md exists; validate --strict warns on it (DR-81)"));
            }
        } else if fs::read_to_string(&claude).ok().as_deref().map(str::trim) != Some("@AGENTS.md") {
            problems.push(format!("{dir}/CLAUDE.md must exist and hold the one line `@AGENTS.md`"));
        }
    }
    for area in &rows {
        problems.extend(may_depend_problems(area, rules));
    }
    Ok(problems)
}

/// The code spans in a cell.
fn code_spans(cell: &str) -> BTreeSet<String> {
    cell.split('`').skip(1).step_by(2).map(str::to_owned).collect()
}

/// A crate row's "May depend on" names exactly its `may_depend` and `external_allow`; a package
/// row names only what its `may_import`, `third_party` and `host_types` hold. A glob such as
/// `tree-sitter-*` or `@fontsource/*` matches the cell's code span of its stem.
fn may_depend_problems(area: &Area, rules: &Boundaries) -> Vec<String> {
    let words = ["boundaries.toml", "third_party", "host_types"];
    let named: BTreeSet<String> =
        code_spans(&area.may).into_iter().filter(|s| !words.contains(&s.as_str())).collect();
    let stem = |a: &str| a.trim_end_matches('*').trim_end_matches(['-', '/']).to_owned();
    let mut problems = Vec::new();
    if let Some(key) = area.dir.strip_prefix("crates/") {
        let Some(rule) = rules.rust.crates.get(key) else { return problems };
        let Some(allow) = &rule.external_allow else { return problems };
        let mut expected: BTreeSet<String> = allow.iter().map(|a| stem(a)).collect();
        expected.extend(rule.may_depend.iter().filter(|m| *m != "*").cloned());
        let listed: BTreeSet<String> =
            named.iter().filter(|n| !rule.may_depend.contains(n)).cloned().collect();
        let allowed: BTreeSet<String> = allow.iter().map(|a| stem(a)).collect();
        for missing in allowed.difference(&listed) {
            problems.push(format!(
                "{REPO_LAYOUT}: the `{}` row's May depend on cell doesn't name `{missing}`, which its external_allow lists",
                area.dir
            ));
        }
        for extra in named.difference(&expected) {
            problems.push(format!(
                "{REPO_LAYOUT}: the `{}` row's May depend on cell names `{extra}`, which boundaries.toml doesn't allow",
                area.dir
            ));
        }
    } else if let Some(rule) = rules.ts.packages.iter().find_map(|(name, rule)| {
        (area.dir == format!("packages/{name}") || area.dir == format!("tests/{name}")).then_some(rule)
    }) {
        let mut expected: BTreeSet<String> =
            rule.may_import.iter().map(|m| format!("@planroom/{m}")).collect();
        expected.extend(rule.third_party.iter().map(|t| stem(t)));
        expected.extend(rule.host_types.iter().cloned());
        for extra in named.difference(&expected) {
            problems.push(format!(
                "{REPO_LAYOUT}: the `{}` row's May depend on cell names `{extra}`, which boundaries.toml doesn't allow",
                area.dir
            ));
        }
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_cells_ignore_formatting() {
        let a = "## T\n\n| A | B |\n|---|---|\n| `x` | one  two |\n";
        let b = "## T\n| A    | B        |\n| :-- | --- |\n|`x`|one two|\n\nafter\n";
        assert_eq!(table_rows(a, "## T"), table_rows(b, "## T"));
        assert_eq!(table_rows(a, "## T")[1], vec!["`x`", "one two"]);
        assert_eq!(split_row("| `a|b` | c |"), vec!["`a|b`", "c"]);
    }

    #[test]
    fn links_are_rewritten_for_the_area() {
        assert_eq!(
            relink("[C](contracts.md); x", "crates/contract"),
            "[C](../../docs/contributing/contracts.md); x"
        );
        assert_eq!(
            relink("[E](#the-one-task-entry-point)", "plugin"),
            "[E](../docs/contributing/repo-layout.md#the-one-task-entry-point)"
        );
        assert_eq!(relink("[A](../../AGENTS.md#dependencies)", "docs"), "[A](../AGENTS.md#dependencies)");
    }

    #[test]
    fn slugs_match_github_anchors() {
        assert_eq!(
            slug("Writes: actors, base, conflicts and retries"),
            "writes-actors-base-conflicts-and-retries"
        );
        assert_eq!(slug("The reconciler (R7)"), "the-reconciler-r7");
        assert_eq!(
            slug("DR-79: Gates that fire only where they mean something"),
            "dr-79-gates-that-fire-only-where-they-mean-something"
        );
    }

    #[test]
    fn a_block_replaces_the_hand_written_contract_and_keeps_the_rest() {
        let text = "# `x`\n\nThis area's contract, from here.\n\n- **Owns:** a.\n- **Must not:** b.\n\n## Layout\n\n- `src/`: code.\n";
        let placed = place(text, &format!("{BEGIN}\nnew\n{END}"));
        assert_eq!(placed, format!("# `x`\n\n{BEGIN}\nnew\n{END}\n\n## Layout\n\n- `src/`: code.\n"));
        assert_eq!(place(&placed, &format!("{BEGIN}\nnewer\n{END}")), placed.replace("new\n", "newer\n"));
        let bare = "# `y`\n\n## Layout\n";
        assert_eq!(place(bare, "B"), "# `y`\n\nB\n\n## Layout\n");
    }
}
